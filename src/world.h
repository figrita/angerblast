// world.h - the GameWorld aggregate. Each system owns its own struct; GameWorld owns
// them all plus run-level state. A single `GameWorld *w` is threaded through the systems
// so there are no hidden globals.
#ifndef ANGERBLAST_WORLD_H
#define ANGERBLAST_WORLD_H

#include "core/common.h"
#include "data/weapons_def.h"
#include "data/analytics.h"

// ---- a socketed weapon instance ----
typedef struct {
    int   type;             // WeaponId, or -1 if the slot is empty
    int   level;            // weapon's own level (still upgradable)
    int   runes[SOCKETS];   // RuneId per socket, or RUNE_NONE
    int   evolution;        // TrifectaId once the 3 runes form one, else -1
    float timer;            // per-weapon fire cooldown
} Weapon;

typedef struct {
    Weapon items[MAX_WEAPONS];
    int    count;           // weapons currently held
} Loadout;

// ---- a companion drone: one socketed weapon + a movement AI. Reuses Weapon so the rune /
// trifecta / evolution machinery applies to a drone's gun for free. ----
#define MAX_DRONES 6
typedef struct {
    Vector2 pos, vel;
    int     ai;             // DroneAI: follow / auto / sweep
    Weapon  weapon;         // the drone's own gun (its own sockets)
    float   t;              // age, for sweep timing
    int     sweepDir;       // sweep direction (+1/-1)
    int     orbitSlot;      // follow: which trailing slot (spreads multiple followers out)
    bool    active;
} Drone;

typedef struct {
    Drone items[MAX_DRONES];
    int   count;
} DroneBay;

// ---- per-system state ----

typedef struct {
    short cell[GRID_CELLS * GRID_CELLS][CELL_CAP];
    unsigned char n[GRID_CELLS * GRID_CELLS];
} Grid;

typedef struct { Bullet items[MAX_BULLETS]; int cursor; } BulletPool;
typedef struct { Enemy items[MAX_ENEMIES]; int cursor; } EnemyPool;
typedef struct { Gem items[MAX_GEMS]; int cursor; } GemPool;
typedef struct { Pickup items[MAX_PICKUPS]; int cursor; } PickupPool;
typedef struct { Puddle items[MAX_PUDDLES]; int cursor; } PuddlePool;

typedef struct {
    Particle parts[MAX_PARTICLES]; int partCursor;
    DamageNum dmg[MAX_DMGNUM]; int dmgCursor;
    Bolt bolts[MAX_BOLTS]; int boltCursor;
    Ring rings[MAX_RINGS]; int ringCursor;
} FxPool;

// Wave/formation director state.
typedef struct {
    int   wavesThisStage;   // formations spawned in the current stage
    int   wavesPerStage;    // how many before the boss
    float waveTimer;        // delay before next formation
    bool  bossPending;      // all waves done, waiting to summon boss
    // formation-clear tracking: a wave is "live" once spawned; when the field empties we
    // reward a gem burst (at the last kill's XY) + grant a short LULL before the next wave.
    bool  waveLive;         // a formation is on the field, not yet cleared
} Director;

// Roguelite level-up state. A level-up offers 3 cards; some are runes which then need
// placing into a weapon socket (the placement sub-step).
typedef enum { PICK_CARD, PICK_SOCKET } LevelupPhase;

typedef struct {
    int  cards[3];          // CardId per offered card (see upgrades_sys.h)
    int  hover;             // hovered card index, or during placement the weapon index
    int  pending;           // queued level-ups not yet resolved
    LevelupPhase phase;     // choosing a card, or placing a rune
    int  placingRune;       // RuneId being placed (PICK_SOCKET phase), else RUNE_NONE
} Cards;

// In-game encyclopedia navigation: which category tab + scroll offset within it.
typedef struct {
    int tab;        // CodexTab
    int scroll;     // first visible entry index
} Codex;

// Sound bank: wav files from assets/audio/<name>.wav (generated by
// tools/audio/gen_sfx.py), with a per-event procedural synth fallback when a
// file is missing. Music streams per biome from assets/audio/music_<slug>.ogg.
typedef enum {
    SFX_SHOOT, SFX_HIT, SFX_EXPLODE, SFX_PICKUP, SFX_LEVELUP, SFX_BOSS_DIE,
    SFX_DODGE, SFX_UI_MOVE, SFX_UI_SELECT,
    SFX_CHARGE, SFX_CHARGE_STEP, SFX_CHARGE_FULL, SFX_SHOOT_BIG,
    SFX_COUNT
} SfxId;
typedef struct {
    Sound snd[SFX_COUNT];
    Music music;
    bool  musicLoaded;
    char  musicSlug[32];   // biome slug the current stream belongs to
    float musicVol;        // current fade level (crossfade on biome change)
    float killThrottle, pickThrottle;
} AudioBank;

// ---- the aggregate ----
typedef struct GameWorld {
    Player     player;
    Loadout    loadout;
    DroneBay   drones;
    Boss       boss;
    BulletPool bullets;
    EnemyPool  enemies;
    GemPool    gems;
    PickupPool pickups;
    PuddlePool puddles;
    FxPool     fx;
    Grid       grid;
    Director   director;
    Cards      cardsel;
    Codex      codex;
    Analytics  analytics;
    AudioBank  audio;

    GameState  state;
    double     runTime, score, bestScore;
    int        stage, kills;
    int        biome;          // current biome index (outer progression), wraps at NUM_BIOMES
    int        loopCount;      // times the biome roster has wrapped back to 01_void (0 = first pass)
    float      shakeAmount, hitFlash, bossWarnTimer;
    int        pauseDragRow;   // pause-menu volume slider being mouse-dragged, or -1 (not per-run state)

    // ---- game-feel (cosmetic) ----
    float      hitstop;        // seconds of near-freeze left (kills/explosions punch)
    float      clearFlash;     // full-screen white flash (stage clear), 0..1 decaying
    float      muzzleFlash;    // player main-gun muzzle flash + recoil timer
    float      stageBannerTimer;      // >0 while the stage-clear slam banner shows
    const char *stageBannerText;      // "HELL YEAH!" flavor line
    const char *stageBannerSub;       // next biome name (points at stageBannerSubBuf, or a literal)
    char       stageBannerSubBuf[48]; // backing storage for a formatted stageBannerSub (outlives TextFormat's rotating buffer)

    // transient "WEAPON EVOLVED" announcement banner
    float       evoBannerTimer;     // >0 while showing
    const char *evoBannerName;      // evolution name
    const char *evoBannerDesc;      // what it does

    int bulletOnHit;   // HIT_* stamped onto bullets created by the next bullets_add calls
    int bulletStyle;   // BSTYLE_* stamped onto the next friendly bullets
    float bulletSplashR;   // HIT_SPLASH radius stamped onto the next friendly bullets
    bool  maingunTapFire;  // one-frame: manual (autofire-off) tap volley requested
    int   bulletEffect;    // EffectId applied on hit, or -1
    float bulletEffectMag; // magnitude for that effect
    bool  bulletMagnetKill;// Prospector: stamp magnetKill onto the next bullets
    int   bulletOnKill;    // OnKill behaviour stamped onto the next bullets
    int   bulletBounce;    // Ricochet: bounces stamped onto the next bullets
    bool  bulletCrit;      // Marksman: stamp guaranteed crit onto the next bullets
    bool  bulletDestroysBullets;  // Aegis gem: friendly bullets shoot down enemy bullets
    short bulletSrcType;          // enemy type firing the next enemy bullets (analytics blame), or -1

    Rng   rng;             // deterministic per-run RNG (seeded in game_reset); owned here so
                           // runs reproduce from a seed and Monte-Carlo forks diverge cleanly
    int   pilot;           // PilotMode: who's flying (HUMAN keyboard/pad, or the BOT)
    Vector2 lastKillPos;   // where the most recent enemy died (formation-clear burst origin)
} GameWorld;

// Gameplay RNG wrappers — ALWAYS use these in sim code (never raylib's global RNG), so runs
// are deterministic. `w->rng` is the single owned stream.
static inline float frand(GameWorld *w)                 { return rng_f(&w->rng); }
static inline float frandr(GameWorld *w, float a, float b) { return rng_fr(&w->rng, a, b); }
static inline int   irand(GameWorld *w, int lo, int hi) { return rng_i(&w->rng, lo, hi); }

#endif // ANGERBLAST_WORLD_H
